import { afterEach, expect, it, vi } from 'vitest';
import { DiagnosticScheduler } from './diagnosticScheduler';
afterEach(() => vi.useRealTimers());
it('coalesces edits at the configured delay and reschedules live', async () => {
  vi.useFakeTimers();
  const published: number[] = [];
  const scheduler = new DiagnosticScheduler(async () => 1, value => published.push(value));
  scheduler.schedule(300);
  await vi.advanceTimersByTimeAsync(250);
  scheduler.schedule(100);
  await vi.advanceTimersByTimeAsync(99);
  expect(published).toEqual([]);
  await vi.advanceTimersByTimeAsync(1);
  expect(published).toEqual([1]);
  scheduler.dispose();
});
it('never publishes an old async result after a newer edit', async () => {
  vi.useFakeTimers();
  const pending: Array<(value: number) => void> = [];
  const published: number[] = [];
  const scheduler = new DiagnosticScheduler(() => new Promise<number>(resolve => pending.push(resolve)), value => published.push(value));
  scheduler.schedule(0);
  await vi.advanceTimersByTimeAsync(0);
  scheduler.schedule(0);
  await vi.advanceTimersByTimeAsync(0);
  pending[1](2);
  await Promise.resolve();
  pending[0](1);
  await Promise.resolve();
  expect(published).toEqual([2]);
  scheduler.dispose();
});
it('disposes timers and in-flight work', async () => {
  vi.useFakeTimers();
  const published: number[] = [];
  let resolve!: (value: number) => void;
  const scheduler = new DiagnosticScheduler(() => new Promise<number>(done => { resolve = done; }), value => published.push(value));
  scheduler.schedule(0);
  await vi.advanceTimersByTimeAsync(0);
  scheduler.dispose();
  resolve(1);
  await Promise.resolve();
  scheduler.schedule(1);
  await vi.advanceTimersByTimeAsync(1);
  expect(published).toEqual([]);
});
it('reports only current failures and can recover', async () => {
  vi.useFakeTimers();
  const errors: unknown[] = [];
  const published: number[] = [];
  let fail = true;
  const scheduler = new DiagnosticScheduler(async () => { if (fail) throw Error('read failed'); return 2; }, value => published.push(value), error => errors.push(error));
  scheduler.schedule(0);
  await vi.advanceTimersByTimeAsync(0);
  expect(errors).toHaveLength(1);
  fail = false;
  scheduler.schedule(0);
  await vi.advanceTimersByTimeAsync(0);
  expect(published).toEqual([2]);
});
